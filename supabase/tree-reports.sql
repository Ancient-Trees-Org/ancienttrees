-- Reports on a tree and moved pins in a table of their own: step 2 of
-- splitting submissions (Hidde, 2026-11-16: worth-it votes and tree
-- submissions are "hele andere dingen", the one catch-all table "een troep";
-- step 1 was tree-votes.sql, step 2 "later als het rustiger is").
--
-- Until now "Something's wrong" was a submissions row with why "report:
-- <chip>", its optional follow-up a SECOND row "report detail: <words>", and
-- a pin dragged on the map a "correction" row with the coordinate in
-- location_hint. Every script that counted trees people sent had to guess
-- which rows were these. Here a report is one row: which tree, the reason,
-- the person's words filled in place when they arrive, the coordinate for a
-- pin, and the verdict and reply a run gives it.
--
-- What STAYS in submissions: trees and places people send (kind tree, city),
-- ambassador requests, privacy requests, and general typed feedback.
--
-- Paste this once into the Supabase SQL editor (dashboard > SQL) and run it.
-- Everything in it is idempotent; running it twice is safe. It runs as one
-- transaction: if any part fails, nothing is changed.
--
-- Design notes:
-- * The name is tree_reports: public.reports is taken (reports about a
--   person, App Store guideline 1.2, reports.sql).
-- * references auth.users on delete cascade: deleting the account deletes the
--   reports, so account deletion stays end to end (hard list 1).
-- * RLS: a person reads only their own rows, and may insert only a bare
--   report of their own (no verdict, no reply). Verdicts and replies are
--   written by the night run with the service key.
-- * THE APPS ALREADY IN PEOPLE'S POCKETS, and the website, keep posting
--   reports to submissions. The trigger at the bottom catches every
--   report-shaped row on its way in, writes it here, and drops it from
--   submissions (return null; PostgREST still answers 201, so the sender sees
--   success). A "report detail" fills the detail of that person's latest
--   open report on the same tree instead of becoming a row of its own.
-- * Old rows in submissions are copied (submission_id says which) and left
--   where they are: nothing is deleted (hard list 3). Only accounts that
--   still exist are copied (the first tree-votes paste stopped on a deleted
--   account's foreign key); the few rows without an account stay readable in
--   submissions, and every script reads those as before.
-- * GRANT in the same file (Supabase stopped granting API access
--   automatically on 2026-10-30; CLAUDE.md, Privacy and accounts).

create table if not exists public.tree_reports (
  -- Starts at a million so an id never equals a submissions id: scripts read
  -- both tables in one list, and skip a few submissions ids as test rows.
  id            bigint generated by default as identity (start with 1000001) primary key,
  user_id       uuid not null default auth.uid() references auth.users (id) on delete cascade,
  -- Our tree id when the sender named one ("kyo_016"); null when they sent
  -- only a name or a sighting id (the apps' pin moves send the name).
  tree_id       text check (tree_id is null or char_length(tree_id) <= 40),
  -- The tree field as it was sent: "<id> (<name>)", a name, or a sighting id.
  tree          text check (tree is null or char_length(tree) <= 300),
  -- A report chip ('dead or gone', 'wrong location', 'could not tell which
  -- tree', 'could not reach it', 'on the map twice', 'something else'), or
  -- 'pin moved', 'collected far', 'merged', 'correction' (typed).
  reason        text not null check (char_length(reason) between 1 and 60),
  -- The person's words: the follow-up to a chip, or the correction's text.
  detail        text check (detail is null or char_length(detail) <= 4000),
  detail_at     timestamptz,
  -- A pin: the coordinate, and location_hint as sent (it may carry a note on
  -- the GPS fix after the numbers).
  lat           double precision check (lat is null or lat between -90 and 90),
  lng           double precision check (lng is null or lng between -180 and 180),
  location_hint text check (location_hint is null or char_length(location_hint) <= 300),
  city          text,
  page          text,
  created_at    timestamptz not null default now(),
  -- The review fields, as submissions has them (contributor-reply.sql).
  outcome       text check (outcome is null or outcome in ('changed', 'holds', 'open_question')),
  reply_text    text,
  replied_at    timestamptz,
  thanked_at    timestamptz,
  -- The submissions row this came from, for rows copied by this file.
  submission_id        bigint unique,
  detail_submission_id bigint unique
);

create index if not exists tree_reports_user_id on public.tree_reports (user_id);
create index if not exists tree_reports_tree_id on public.tree_reports (tree_id);
create index if not exists tree_reports_created_at on public.tree_reports (created_at);

alter table public.tree_reports enable row level security;

drop policy if exists "own reports select" on public.tree_reports;
create policy "own reports select" on public.tree_reports
  for select using (auth.uid() = user_id);

drop policy if exists "own reports insert" on public.tree_reports;
create policy "own reports insert" on public.tree_reports
  for insert with check (
    auth.uid() = user_id
    and outcome is null and reply_text is null
    and replied_at is null and thanked_at is null
    and submission_id is null and detail_submission_id is null);

-- An identity column needs no grant on its sequence.
grant select, insert on public.tree_reports to authenticated;
grant select, insert, update on public.tree_reports to service_role;

-- Which rows of submissions are reports. One rule, used by the copy and by
-- the trigger.
create or replace function public.is_tree_report(kind text, why text)
returns boolean
language sql
immutable
as $$
  select coalesce(kind, '') = 'correction'
      or (coalesce(kind, '') = 'feedback'
          and (lower(trim(coalesce(why, ''))) = 'report'
               or lower(trim(coalesce(why, ''))) like 'report:%'
               or lower(trim(coalesce(why, ''))) like 'report detail%'))
$$;

-- The reason of one report-shaped row (not a "report detail").
create or replace function public.tree_report_reason(why text)
returns text
language sql
immutable
as $$
  select case
    when w like 'report:%' then coalesce(nullif(left(trim(substr(w, 8)), 60), ''), 'something else')
    when w = 'report' then 'something else'
    when w like 'moved the pin%' then 'pin moved'
    when w like 'collected with a photograph%' then 'collected far'
    when w like 'could not tell which tree%' or w like 'not clear which tree%' then 'could not tell which tree'
    when w like 'a tree the person added, merged%' then 'merged'
    else 'correction'
  end
  from (select lower(trim(coalesce(why, ''))) as w) x
$$;

-- Our tree id out of the tree field, or null ("kyo_016 (Sudajii ...)" gives
-- kyo_016; "Major Oak" and a sighting's uuid give null).
create or replace function public.tree_report_tree_id(tree text)
returns text
language sql
immutable
as $$
  select case when split_part(coalesce(tree, ''), ' ', 1) ~ '^[a-z0-9]+(-[a-z0-9]+)*_[a-z0-9_-]+$'
              then left(split_part(tree, ' ', 1), 40) end
$$;

-- The words after "report detail: ".
create or replace function public.tree_report_detail_words(why text)
returns text
language sql
immutable
as $$
  select left(trim(regexp_replace(coalesce(why, ''), '^\s*report detail\s*:?\s*', '', 'i')), 4000)
$$;

-- The first two numbers in location_hint, as a coordinate.
create or replace function public.tree_report_coord(hint text, part int)
returns double precision
language sql
immutable
as $$
  select case
    when m is not null and (m[1])::double precision between -90 and 90
         and (m[2])::double precision between -180 and 180
    then (m[part])::double precision end
  from (select regexp_match(coalesce(hint, ''),
          '^\s*(-?[0-9]+(?:\.[0-9]+)?)\s*,\s*(-?[0-9]+(?:\.[0-9]+)?)') as m) x
$$;

-- COPY. First every report and correction (not the follow-ups), oldest
-- first, with the verdict and reply fields they already carry.
insert into public.tree_reports (user_id, tree_id, tree, reason, detail, lat, lng, location_hint,
                                 city, page, created_at, outcome, reply_text, replied_at,
                                 thanked_at, submission_id)
select s.user_id,
       public.tree_report_tree_id(s.tree),
       left(s.tree, 300),
       public.tree_report_reason(s.why),
       case when s.kind = 'correction' then left(s.why, 4000) end,
       public.tree_report_coord(s.location_hint, 1),
       public.tree_report_coord(s.location_hint, 2),
       left(s.location_hint, 300),
       s.city, s.page, s.created_at,
       case when s.outcome in ('changed', 'holds', 'open_question') then s.outcome end,
       s.reply_text, s.replied_at, s.thanked_at, s.id
from public.submissions s
where public.is_tree_report(s.kind, s.why)
  and not (s.kind = 'feedback' and lower(trim(coalesce(s.why, ''))) like 'report detail%')
  and s.user_id is not null
  and exists (select 1 from auth.users u where u.id = s.user_id)
order by s.created_at
on conflict (submission_id) do nothing;

-- Then each old follow-up fills the detail of the same person's latest report
-- on the same tree written before it; one with no such report becomes a row
-- of its own ('something else').
do $$
declare
  d record;
  target bigint;
begin
  for d in
    select s.* from public.submissions s
    where s.kind = 'feedback'
      and lower(trim(coalesce(s.why, ''))) like 'report detail%'
      and s.user_id is not null
      and exists (select 1 from auth.users u where u.id = s.user_id)
      and not exists (select 1 from public.tree_reports r where r.detail_submission_id = s.id)
    order by s.created_at
  loop
    select r.id into target from public.tree_reports r
     where r.user_id = d.user_id
       and coalesce(r.tree_id, r.tree) = coalesce(public.tree_report_tree_id(d.tree), left(d.tree, 300))
       and r.detail is null
       and r.reason not in ('pin moved', 'collected far', 'merged', 'correction')
       and r.created_at <= d.created_at
     order by r.created_at desc limit 1;
    if target is not null then
      update public.tree_reports
         set detail = public.tree_report_detail_words(d.why), detail_at = d.created_at,
             detail_submission_id = d.id,
             outcome = coalesce(outcome, case when d.outcome in ('changed', 'holds', 'open_question') then d.outcome end),
             reply_text = coalesce(reply_text, d.reply_text),
             replied_at = coalesce(replied_at, d.replied_at),
             thanked_at = coalesce(thanked_at, d.thanked_at)
       where id = target;
    else
      insert into public.tree_reports (user_id, tree_id, tree, reason, detail, detail_at, city, page,
                                       created_at, outcome, reply_text, replied_at, thanked_at,
                                       detail_submission_id)
      values (d.user_id, public.tree_report_tree_id(d.tree), left(d.tree, 300), 'something else',
              public.tree_report_detail_words(d.why), d.created_at, d.city, d.page, d.created_at,
              case when d.outcome in ('changed', 'holds', 'open_question') then d.outcome end,
              d.reply_text, d.replied_at, d.thanked_at, d.id);
    end if;
    target := null;
  end loop;
end
$$;

-- Catch a report posted to submissions (every build out there, and the
-- website, does this) and write it here instead. Returning null drops the
-- submissions row; PostgREST still answers 201. A row with no account stays
-- in submissions (every report control asks for an account, so this is an
-- old build's edge, and the scripts read those rows there as before).
create or replace function public.submission_report_to_tree_reports()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  w      text := lower(trim(coalesce(new.why, '')));
  uid    uuid := coalesce(new.user_id, auth.uid());
  tid    text := public.tree_report_tree_id(new.tree);
  target bigint;
begin
  if not public.is_tree_report(new.kind, new.why) then
    return new;
  end if;
  if uid is null then
    return new;
  end if;
  if new.kind = 'feedback' and w like 'report detail%' then
    select r.id into target from public.tree_reports r
     where r.user_id = uid
       and coalesce(r.tree_id, r.tree) = coalesce(tid, left(new.tree, 300))
       and r.detail is null
       and r.reason not in ('pin moved', 'collected far', 'merged', 'correction')
     order by r.created_at desc limit 1;
    if target is not null then
      update public.tree_reports
         set detail = public.tree_report_detail_words(new.why), detail_at = now()
       where id = target;
    else
      insert into public.tree_reports (user_id, tree_id, tree, reason, detail, detail_at, city, page)
      values (uid, tid, left(new.tree, 300), 'something else',
              public.tree_report_detail_words(new.why), now(), new.city, new.page);
    end if;
    return null;
  end if;
  insert into public.tree_reports (user_id, tree_id, tree, reason, detail, lat, lng,
                                   location_hint, city, page)
  values (uid, tid, left(new.tree, 300), public.tree_report_reason(new.why),
          case when new.kind = 'correction' then left(new.why, 4000) end,
          public.tree_report_coord(new.location_hint, 1),
          public.tree_report_coord(new.location_hint, 2),
          left(new.location_hint, 300), new.city, new.page);
  return null;
end
$$;

drop trigger if exists submissions_reports_to_tree_reports on public.submissions;
create trigger submissions_reports_to_tree_reports
  before insert on public.submissions
  for each row execute function public.submission_report_to_tree_reports();
